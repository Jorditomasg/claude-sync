export const strings: Record<Lang, Strings> = { en, es }

export function detectLang (setting: unknown, env: { LC_ALL?: string; LC_MESSAGES?: string; LANG?: string }, runtime?: string): Lang {
  if (typeof setting === 'string' && setting.trim()) return /^(es|spa|españ|spanish)/i.test(setting.trim()) ? 'es' : 'en'
  const locale = [env.LC_ALL, env.LC_MESSAGES, env.LANG].find(v => v && v !== 'C' && v !== 'POSIX') ?? runtime ?? ''
  return /^es([_-]|$)/i.test(locale) ? 'es' : 'en'
}
